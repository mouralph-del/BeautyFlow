create or replace function public.enqueue_automation_email(
  target_recipient text, target_template text, target_preference text,
  target_event_key text, target_variables jsonb default '{}'::jsonb,
  target_metadata jsonb default '{}'::jsonb
) returns bigint language plpgsql security definer set search_path=public as $$
declare result bigint; selected_priority text;
begin
  if nullif(trim(target_recipient),'') is null then return null; end if;
  select coalesce(priority,'normal') into selected_priority from public.notification_preferences where id=target_preference;
  insert into public.automation_email_outbox(recipient,template_id,preference_id,event_key,priority,variables,metadata)
  values(lower(trim(target_recipient)),target_template,target_preference,target_event_key,coalesce(selected_priority,'normal'),coalesce(target_variables,'{}'),coalesce(target_metadata,'{}'))
  on conflict(event_key) do nothing returning id into result;
  return result;
end $$;

create or replace function public.claim_automation_email_outbox(batch_size integer default 50, worker_name text default 'worker')
returns setof public.automation_email_outbox language plpgsql security definer set search_path=public as $$
begin
  return query with claimed as (
    select id from public.automation_email_outbox
    where (status='pending' or (status='processing' and locked_at<now()-interval '15 minutes'))
      and attempts<5 and next_attempt_at<=now()
    order by case priority when 'high' then 1 when 'normal' then 2 else 3 end, created_at
    for update skip locked limit greatest(1,least(batch_size,100))
  ) update public.automation_email_outbox o set status='processing',attempts=attempts+1,locked_at=now(),locked_by=worker_name,updated_at=now()
    from claimed where o.id=claimed.id returning o.*;
end $$;

create or replace function public.complete_automation_email(job_id bigint, was_sent boolean, error_text text default null)
returns void language plpgsql security definer set search_path=public as $$
declare job public.automation_email_outbox%rowtype;
begin
  select * into job from public.automation_email_outbox where id=job_id for update;
  if not found then return; end if;
  if was_sent then
    update public.automation_email_outbox set status='sent',sent_at=now(),last_error=null,updated_at=now() where id=job_id;
    if job.metadata->>'kind'='reminder_24h' then update public.appointments set reminder_sent_at=now() where id=(job.metadata->>'appointment_id')::uuid; end if;
    if job.metadata->>'kind'='promotion' then
      insert into public.promotion_email_history(promotion_id,customer_id,recipient,outbox_id)
      values((job.metadata->>'promotion_id')::uuid,(job.metadata->>'customer_id')::uuid,job.recipient,job.id) on conflict do nothing;
    end if;
  elsif error_text='disabled' then
    update public.automation_email_outbox set status='skipped',last_error=error_text,updated_at=now() where id=job_id;
  else
    update public.automation_email_outbox set status=case when attempts>=5 then 'failed' else 'pending' end,last_error=left(error_text,1000),next_attempt_at=now()+make_interval(mins=>least(60,attempts*10)),updated_at=now() where id=job_id;
  end if;
end $$;

create or replace function public.automation_appointment_email_trigger() returns trigger language plpgsql security definer set search_path=public as $$
declare vars jsonb; names text;
begin
  select coalesce(string_agg(service_name,', '),new.service_name,'Atendimento') into names from public.appointment_services where appointment_id=new.id;
  vars:=jsonb_build_object('customer_name',new.customer_name,'appointment_date',to_char(new.appointment_date,'DD/MM/YYYY'),'appointment_time',left(new.appointment_time,5),'service_name',names);
  if tg_op='INSERT' and new.payment_status='em_analise' then perform public.enqueue_automation_email(new.email,'payment_review','payment_analysis','payment-review:'||new.id,vars,jsonb_build_object('appointment_id',new.id)); end if;
  if tg_op='UPDATE' and new.payment_status is distinct from old.payment_status then
    if new.payment_status in('aprovado','pago','approved') then perform public.enqueue_automation_email(new.email,'payment_confirmed','payment_proof','payment-approved:'||new.id,vars,jsonb_build_object('appointment_id',new.id)); end if;
    if new.payment_status in('recusado','refused','rejeitado') then perform public.enqueue_automation_email(new.email,'payment_refused','payment_refused','payment-rejected:'||new.id,vars,jsonb_build_object('appointment_id',new.id)); end if;
  end if;
  if tg_op='UPDATE' and new.status is distinct from old.status then
    if new.status in('confirmado','confirmed') then perform public.enqueue_automation_email(new.email,'appointment_confirmed','appointment_confirmed','appointment-confirmed:'||new.id,vars,jsonb_build_object('appointment_id',new.id)); end if;
    if new.status='cancelado' then perform public.enqueue_automation_email(new.email,'cancellation','cancellation','appointment-cancelled:'||new.id,vars,jsonb_build_object('appointment_id',new.id)); end if;
  end if;
  return new;
end $$;
