create table if not exists public.email_delivery_logs (
  id bigint generated by default as identity primary key,
  recipient text not null,
  template_id text not null,
  preference_id text not null,
  event_key text not null,
  priority text not null default 'normal',
  status text not null check (status in ('sent','error','skipped')),
  provider_message_id text,
  error_message text,
  sent_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.automation_email_outbox (
  id bigint generated by default as identity primary key,
  recipient text not null,
  template_id text not null,
  preference_id text not null,
  event_key text not null unique,
  priority text not null default 'normal' check (priority in ('low','normal','high')),
  variables jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  status text not null default 'pending' check (status in ('pending','processing','sent','skipped','failed')),
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  locked_at timestamptz,
  locked_by text,
  last_error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.promotion_email_history (
  id bigint generated by default as identity primary key,
  promotion_id uuid not null references public.promotions(id) on delete cascade,
  customer_id uuid not null references auth.users(id) on delete cascade,
  recipient text not null,
  outbox_id bigint references public.automation_email_outbox(id) on delete set null,
  sent_at timestamptz not null default now(),
  unique (promotion_id, customer_id)
);

create table if not exists public.daily_content_history (
  local_date date primary key,
  verse text not null,
  created_at timestamptz not null default now()
);

