create or replace function public.prepare_hourly_automation_emails() returns void language plpgsql security definer set search_path=public as $$
declare a record; local_now timestamp:=(now() at time zone 'America/Sao_Paulo'); local_today date:=(now() at time zone 'America/Sao_Paulo')::date; next_month date;
begin
  for a in select appointments.*,coalesce((select string_agg(service_name,', ') from public.appointment_services s where s.appointment_id=appointments.id),service_name,'Atendimento') names
    from public.appointments where status not in('cancelado','concluido','nao_compareceu','ausente') and reminder_sent_at is null
      and (appointment_date+appointment_time::time) between local_now+interval '23 hours' and local_now+interval '24 hours'
  loop
    perform public.enqueue_automation_email(a.email,'reminder_24h','reminder_24h','reminder-24h:'||a.id,
      jsonb_build_object('customer_name',a.customer_name,'appointment_time',left(a.appointment_time,5),'service_name',a.names),jsonb_build_object('kind','reminder_24h','appointment_id',a.id));
  end loop;
  perform public.create_monthly_schedule_release_reminders();
  if extract(day from local_today) in(20,25) or local_today=(date_trunc('month',local_today)+interval '1 month - 1 day')::date then
    next_month:=(date_trunc('month',local_today)+interval '1 month')::date;
    if not exists(select 1 from public.monthly_schedule_releases where year=extract(year from next_month)::int and month=extract(month from next_month)::int and status='released') then
      perform public.enqueue_automation_email('admin@invalid.local','schedule_release','schedule_release','schedule-release:'||local_today,
        jsonb_build_object('customer_name','Thaís','next_month',to_char(next_month,'MM/YYYY')),jsonb_build_object('kind','schedule_release','requires_admin_email',true));
    end if;
  end if;
end $$;

create or replace function public.prepare_promotion_emails() returns void language plpgsql security definer set search_path=public as $$
declare p record; c record;
begin
  for p in select * from public.promotions where active and (starts_at is null or starts_at<=now()) and (ends_at is null or ends_at>=now()) loop
    for c in select * from public.customer_accounts where is_active and promotions_authorized and promotions_consent_at is not null and promotions_revoked_at is null loop
      if not exists(select 1 from public.promotion_email_history where promotion_id=p.id and customer_id=c.user_id) then
        perform public.enqueue_automation_email(c.email,'promotion','promotion','promotion:'||p.id||':'||c.user_id,
          jsonb_build_object('customer_name',coalesce(c.full_name,split_part(c.email,'@',1)),'promotion_title',p.title,'promotion_description',p.description,'promotion_link',coalesce(p.link,'')),jsonb_build_object('kind','promotion','promotion_id',p.id,'customer_id',c.user_id));
      end if;
    end loop;
  end loop;
end $$;

create or replace function public.prepare_daily_summary_email(admin_email text) returns void language plpgsql security definer set search_path=public as $$
declare d date:=(now() at time zone 'America/Sao_Paulo')::date; verse text; previous text; configured jsonb; hour_value integer:=extract(hour from now() at time zone 'America/Sao_Paulo');
begin
  select history.verse into previous from public.daily_content_history as history order by history.local_date desc limit 1;
  select private_data->'daily_verses' into configured from public.studio_settings where id='main';
  if jsonb_typeof(configured)='array' and jsonb_array_length(configured)>0 then select value#>>'{}' into verse from jsonb_array_elements(configured) where value#>>'{}' is distinct from previous order by random() limit 1; end if;
  verse:=coalesce(verse,case when previous is distinct from 'Tudo posso naquele que me fortalece. — Filipenses 4:13' then 'Tudo posso naquele que me fortalece. — Filipenses 4:13' else 'O Senhor é o meu pastor; nada me faltará. — Salmos 23:1' end);
  insert into public.daily_content_history(local_date,verse) values(d,verse) on conflict(local_date) do update set verse=excluded.verse;
  perform public.enqueue_automation_email(admin_email,'daily_summary','daily_summary','daily-summary:'||d,
    jsonb_build_object('customer_name','Thaís','summary_date',to_char(d,'DD/MM/YYYY'),'greeting',case when hour_value<12 then 'Bom dia' when hour_value<18 then 'Boa tarde' else 'Boa noite' end,
      'appointments',(select count(*) from public.appointments where appointment_date=d and status<>'cancelado'),
      'payments',(select count(*) from public.appointments where payment_status='em_analise'),
      'cancellations',(select count(*) from public.appointments where cancelled_at::date=d),
      'fits',(select count(*) from public.booking_requests where created_at::date=d),
      'reschedules',(select count(*) from public.reschedule_requests where created_at::date=d),
      'new_customers',(select count(*) from public.customer_accounts where created_at::date=d),'verse',verse),jsonb_build_object('kind','daily_summary'));
end $$;

