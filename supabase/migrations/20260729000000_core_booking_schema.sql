create extension if not exists pgcrypto;

create table if not exists public.appointments (
  id uuid primary key default gen_random_uuid(),
  service_id bigint,
  service_name text,
  customer_name text not null,
  phone text not null,
  email text not null,
  notes text,
  appointment_date date not null,
  appointment_time text not null,
  end_time text not null,
  status text not null default 'aguardando_aprovacao',
  payment_status text not null default 'em_analise',
  reservation_paid boolean not null default false,
  image_authorization boolean,
  reservation_policy_accepted boolean not null default false,
  service_price numeric(10, 2) not null default 0,
  reservation_amount numeric(10, 2) not null default 0,
  remaining_amount numeric(10, 2) not null default 0,
  payment_proof text,
  duration_minutes integer not null,
  total_duration_minutes integer not null,
  created_at timestamptz not null default now(),
  constraint appointments_positive_duration
    check (duration_minutes > 0 and total_duration_minutes > 0),
  constraint appointments_reservation_policy_accepted_check
    check (reservation_policy_accepted is true)
);

create table if not exists public.appointment_services (
  id bigint generated by default as identity primary key,
  appointment_id uuid not null references public.appointments(id) on delete cascade,
  service_id bigint not null,
  service_name text not null,
  duration_minutes integer not null check (duration_minutes > 0),
  service_price numeric(10, 2) not null default 0,
  reservation_amount numeric(10, 2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.booking_requests (
  id uuid primary key default gen_random_uuid(),
  service_id bigint,
  service_name text not null,
  duration_minutes integer not null check (duration_minutes > 0),
  total_duration_minutes integer,
  customer_name text not null,
  phone text not null,
  email text not null,
  notes text,
  image_authorization boolean,
  appointment_date date not null,
  appointment_time text not null,
  status text not null default 'pendente',
  total_price numeric(10, 2),
  reservation_amount numeric(10, 2),
  remaining_amount numeric(10, 2),
  payment_proof text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

-- A área da cliente é criada antes do catálogo administrativo e já referencia
-- promoções. Esta definição mínima garante a recriação sequencial do banco; a
-- migração administrativa posterior adiciona os demais campos e políticas.
create table if not exists public.promotions (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null default '',
  link text,
  active boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists appointments_date_idx
  on public.appointments (appointment_date);
create index if not exists appointment_services_appointment_id_idx
  on public.appointment_services (appointment_id);
create index if not exists booking_requests_date_idx
  on public.booking_requests (appointment_date);
create unique index if not exists appointments_unique_date_time
  on public.appointments (appointment_date, appointment_time)
  where status <> 'cancelado';

