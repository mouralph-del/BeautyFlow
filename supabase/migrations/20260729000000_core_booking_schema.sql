create or replace function public.create_appointment_with_services(
  appointment_data jsonb,
  services_data jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  created_appointment public.appointments%rowtype;
begin
  if appointment_data is null then
    raise exception 'appointment_data é obrigatório';
  end if;

  if services_data is null
    or jsonb_typeof(services_data) <> 'array'
    or jsonb_array_length(services_data) = 0 then
    raise exception 'services_data deve conter pelo menos um serviço';
  end if;

  if coalesce(
    (appointment_data ->> 'reservation_policy_accepted')::boolean,
    false
  ) is not true then
    raise exception
      'É necessário aceitar a política de reserva para criar o agendamento';
  end if;

  insert into public.appointments (
    customer_name, phone, email, notes, appointment_date,
    appointment_time, end_time, status, payment_status,
    reservation_paid, image_authorization,
    reservation_policy_accepted, service_price,
    reservation_amount, remaining_amount, payment_proof,
    duration_minutes, total_duration_minutes
  )
  select
    payload.customer_name, payload.phone, payload.email, payload.notes,
    payload.appointment_date, payload.appointment_time, payload.end_time,
    payload.status, payload.payment_status, payload.reservation_paid,
    payload.image_authorization, payload.reservation_policy_accepted,
    payload.service_price, payload.reservation_amount,
    payload.remaining_amount, payload.payment_proof,
    payload.duration_minutes, payload.total_duration_minutes
  from jsonb_populate_record(
    null::public.appointments,
    appointment_data
  ) as payload
  returning * into created_appointment;

  insert into public.appointment_services (
    appointment_id, service_id, service_name, duration_minutes,
    service_price, reservation_amount
  )
  select
    created_appointment.id, service_payload.service_id,
    service_payload.service_name, service_payload.duration_minutes,
    service_payload.service_price, service_payload.reservation_amount
  from jsonb_populate_recordset(
    null::public.appointment_services,
    services_data
  ) as service_payload;

  return to_jsonb(created_appointment);
end;
$$;

revoke all on function public.create_appointment_with_services(jsonb, jsonb)
from public;
grant execute on function public.create_appointment_with_services(jsonb, jsonb)
to anon, authenticated;

do $migration$
begin
  if to_regprocedure('public.get_booked_times(date)') is null then
    execute $function$
      create function public.get_booked_times(target_date date)
      returns table (
        appointment_time text,
        duration_minutes integer
      )
      language sql
      stable
      security definer
      set search_path = public
      as $body$
        select
          appointment.appointment_time,
          coalesce(
            appointment.total_duration_minutes,
            appointment.duration_minutes
          )::integer
        from public.appointments as appointment
        where appointment.appointment_date = target_date
          and appointment.status <> 'cancelado'
        order by appointment.appointment_time;
      $body$
    $function$;
  end if;
end;
$migration$;

revoke all on function public.get_booked_times(date) from public;
grant execute on function public.get_booked_times(date) to anon, authenticated;

