create or replace function public.get_active_promotions(target text default null)
returns table(id uuid,title text,short_description text,full_description text,discount_type text,discount_value numeric,promotional_price numeric,starts_at timestamptz,ends_at timestamptz,button_text text,button_target text,image_path text,apply_to_reservation_fee boolean,applies_to_all_services boolean,service_ids bigint[])
language sql stable security definer set search_path=public as $$
  select p.id,p.title,p.short_description,p.full_description,p.discount_type,p.discount_value,p.promotional_price,p.starts_at,p.ends_at,p.button_text,p.button_target,p.image_path,p.apply_to_reservation_fee,p.applies_to_all_services,
    coalesce(array_agg(ps.service_id) filter(where ps.service_id is not null),'{}')
  from public.promotions p left join public.promotion_services ps on ps.promotion_id=p.id
  where p.status='active' and coalesce(p.starts_at,now())<=now() and coalesce(p.ends_at,now()+interval '100 years')>=now()
    and (p.usage_limit is null or p.usage_count<p.usage_limit)
    and (target is null or (target='home' and p.highlight_home) or (target='customer' and p.highlight_customer_area) or target='services')
  group by p.id order by p.display_order,p.created_at desc;
$$;

create or replace function public.admin_save_promotion(payload jsonb, target_id uuid default null)
returns uuid language plpgsql security definer set search_path=public as $$
declare result_id uuid; service_value jsonb;
begin
  if not public.is_admin() then raise exception 'Acesso administrativo necessário'; end if;
  if coalesce(payload->>'internal_name','')='' or coalesce(payload->>'title','')='' then raise exception 'Nome e título são obrigatórios'; end if;
  if (payload->>'ends_at')::timestamptz <= (payload->>'starts_at')::timestamptz then raise exception 'A data final deve ser posterior à inicial'; end if;
  if payload->>'discount_type'='percentage' and ((payload->>'discount_value')::numeric<=0 or (payload->>'discount_value')::numeric>100) then raise exception 'Percentual deve estar entre 0 e 100'; end if;
  if target_id is null then
    insert into public.promotions(internal_name,title,short_description,full_description,discount_type,discount_value,promotional_price,starts_at,ends_at,status,usage_limit,highlight_home,highlight_customer_area,display_order,button_text,button_target,apply_to_reservation_fee,email_enabled,applies_to_all_services,created_by)
    values(payload->>'internal_name',payload->>'title',coalesce(payload->>'short_description',''),coalesce(payload->>'full_description',''),payload->>'discount_type',nullif(payload->>'discount_value','')::numeric,nullif(payload->>'promotional_price','')::numeric,(payload->>'starts_at')::timestamptz,(payload->>'ends_at')::timestamptz,coalesce(payload->>'status','draft'),nullif(payload->>'usage_limit','')::integer,coalesce((payload->>'highlight_home')::boolean,false),coalesce((payload->>'highlight_customer_area')::boolean,false),coalesce((payload->>'display_order')::integer,0),coalesce(payload->>'button_text','Ver promoção'),coalesce(payload->>'button_target','/servicos'),coalesce((payload->>'apply_to_reservation_fee')::boolean,false),coalesce((payload->>'email_enabled')::boolean,false),coalesce((payload->>'applies_to_all_services')::boolean,false),auth.uid()) returning id into result_id;
  else
    update public.promotions set internal_name=payload->>'internal_name',title=payload->>'title',short_description=coalesce(payload->>'short_description',''),full_description=coalesce(payload->>'full_description',''),discount_type=payload->>'discount_type',discount_value=nullif(payload->>'discount_value','')::numeric,promotional_price=nullif(payload->>'promotional_price','')::numeric,starts_at=(payload->>'starts_at')::timestamptz,ends_at=(payload->>'ends_at')::timestamptz,status=payload->>'status',usage_limit=nullif(payload->>'usage_limit','')::integer,highlight_home=(payload->>'highlight_home')::boolean,highlight_customer_area=(payload->>'highlight_customer_area')::boolean,display_order=(payload->>'display_order')::integer,button_text=payload->>'button_text',button_target=payload->>'button_target',apply_to_reservation_fee=(payload->>'apply_to_reservation_fee')::boolean,email_enabled=(payload->>'email_enabled')::boolean,applies_to_all_services=(payload->>'applies_to_all_services')::boolean,updated_at=now() where id=target_id returning id into result_id;
  end if;
  delete from public.promotion_services where promotion_id=result_id;
  if not coalesce((payload->>'applies_to_all_services')::boolean,false) then
    for service_value in select * from jsonb_array_elements(coalesce(payload->'service_ids','[]'::jsonb)) loop
      insert into public.promotion_services(promotion_id,service_id) select result_id,(service_value#>>'{}')::bigint from public.services where id=(service_value#>>'{}')::bigint and is_active;
    end loop;
  end if;
  insert into public.promotion_activity(promotion_id,action,performed_by,details) values(result_id,case when target_id is null then 'created' else 'updated' end,auth.uid(),payload);
  return result_id;
end $$;

create or replace function public.admin_change_promotion(target_id uuid,new_status text)
returns void language plpgsql security definer set search_path=public as $$ begin
 if not public.is_admin() then raise exception 'Acesso negado'; end if;
 if new_status not in ('active','paused','ended') then raise exception 'Status inválido'; end if;
 update public.promotions set status=new_status,active=(new_status='active'),ended_at=case when new_status='ended' then now() else ended_at end,updated_at=now() where id=target_id;
 insert into public.promotion_activity(promotion_id,action,performed_by) values(target_id,new_status,auth.uid());
end $$;

create or replace function public.admin_duplicate_promotion(target_id uuid)
returns uuid language plpgsql security definer set search_path=public as $$ declare result uuid; begin
 if not public.is_admin() then raise exception 'Acesso negado'; end if;
 insert into public.promotions(internal_name,title,short_description,full_description,discount_type,discount_value,promotional_price,status,usage_count,highlight_home,highlight_customer_area,display_order,button_text,button_target,apply_to_reservation_fee,email_enabled,applies_to_all_services,created_by)
 select internal_name||' — Cópia',title,short_description,full_description,discount_type,discount_value,promotional_price,'draft',0,false,false,display_order,button_text,button_target,apply_to_reservation_fee,email_enabled,applies_to_all_services,auth.uid() from public.promotions where id=target_id returning id into result;
 insert into public.promotion_services(promotion_id,service_id) select result,service_id from public.promotion_services where promotion_id=target_id;
 insert into public.promotion_activity(promotion_id,action,performed_by,details) values(result,'duplicated',auth.uid(),jsonb_build_object('source',target_id)); return result;
end $$;

