update public.promotions set
  internal_name = coalesce(nullif(internal_name,''), title),
  short_description = coalesce(nullif(short_description,''), description),
  full_description = coalesce(nullif(full_description,''), description),
  button_target = coalesce(nullif(button_target,''), link, '/servicos'),
  status = case when active then 'active' else coalesce(status,'draft') end
where internal_name is null or internal_name = '';

